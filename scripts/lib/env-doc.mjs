// Reads the server's configuration schema (apps/server/src/config/env.ts) and renders the configuration reference
// (docs/configuration.md). The schema is the source: its doc comments, defaults and types.

/** @typedef {{ name: string, type: string, default: string | null, required: boolean, doc: string }} Setting */

const clean = (s) => s.replace(/\s+/g, ' ').trim();

/** The settings of `envSchema`, in order, with their doc comment, type and default. */
export function parseEnvSchema(source) {
  const start = source.indexOf('const envSchema = z.object({');
  const end = source.indexOf('}).superRefine', start);
  if (start < 0 || end < 0) throw new Error('envSchema not found in env.ts');
  const body = source.slice(start, end).split(/\r?\n/).slice(1);
  /** @type {Setting[]} */
  const out = [];
  let doc = [];
  let inDoc = false;
  let current = null;
  const finish = () => {
    if (!current) return;
    const def = current.def.join(' ');
    const dflt = /\.default\(([^)]*)\)/.exec(def)?.[1]?.trim() ?? null;
    let type = 'string';
    if (/^bool\b/.test(def) || /\bbool\b/.test(def)) type = 'boolean';
    else if (/z\.coerce\.number\(\)/.test(def)) type = /\.int\(\)/.test(def) ? 'integer' : 'number';
    else if (/^z\.enum\(\[/.test(def))
      type = `one of ${[...(/^z\.enum\(\[([^\]]*)\]/.exec(def)?.[1] ?? '').matchAll(/'([^']+)'/g)].map((m) => `\`${m[1]}\``).join(', ')}`;
    else if (/^originList/.test(def)) type = 'comma-separated origins';
    else if (/^z\.url\(\)/.test(def)) type = 'URL';
    const optional = /\.optional\(\)/.test(def) || dflt !== null || /^originList/.test(def);
    out.push({
      name: current.name,
      type,
      default: dflt === null ? null : dflt.replace(/^'(.*)'$/, '$1'),
      required: !optional,
      doc: clean(current.doc.join(' ')),
    });
    current = null;
  };
  for (const raw of body) {
    const line = raw.trim();
    if (line.startsWith('/**')) {
      finish();
      inDoc = !line.endsWith('*/');
      doc = [line.replace(/^\/\*\*\s?/, '').replace(/\*\/$/, '')];
      continue;
    }
    if (inDoc) {
      if (line.endsWith('*/')) inDoc = false;
      if (line !== '*/') doc.push(line.replace(/^\*\s?/, '').replace(/\*\/$/, ''));
      continue;
    }
    const field = /^([A-Z][A-Z0-9_]+):\s*(.*)$/.exec(line);
    if (field) {
      finish();
      current = { name: field[1], def: [field[2]], doc };
      doc = [];
      continue;
    }
    if (current && line && !line.startsWith('//')) current.def.push(line);
  }
  finish();
  return out;
}

const esc = (s) => s.replace(/\|/g, '\\|');

/** The Markdown reference. */
export function renderConfiguration(settings) {
  const rows = settings.map(
    (s) =>
      `| \`${s.name}\` | ${s.required ? '**required**' : s.default !== null ? `\`${esc(s.default)}\`` : '(unset)'} | ${esc(s.type)} | ${esc(s.doc) || ' '} |`,
  );
  return `<!-- Generated by \`node scripts/env-doc.mjs\` from apps/server/src/config/env.ts. Do not edit by hand: change the schema's doc comments and run the script (a test fails when this file is out of date). -->

# Configuration reference

The server reads its settings from the environment (in development also from the repository's \`.env\`). It refuses to start
when a value is invalid and lists every problem; in production it also refuses placeholder secrets (\`change-me…\`).
\`.env.example\` has a commented example of each group, and \`docker-compose.yml\` passes them to the \`server\` container.

| Setting | Default | Type | What it does |
| --- | --- | --- | --- |
${rows.join('\n')}

## Outside the server

| Setting | Where | What it does |
| --- | --- | --- |
| \`OS_PLANNER_API_URL\` | web build (\`npm run build -w @os-planner/web\`) | Address of the API as browsers see it, written to \`config.json\` (env, then \`.env\`, then a question on a terminal; empty = same origin). The server reads the same variable for its CSP. |
| \`OS_PLANNER_SERVER_URL\` | desktop build | The website the desktop window opens (baked in; asked on first start when empty). |
| \`OS_PLANNER_NO_PROMPT\` | web and desktop builds | Never ask on a terminal (CI). |
| \`OS_PLANNER_DOMAIN\`, \`OS_PLANNER_LIVEKIT_DOMAIN\` | compose profile \`proxy\` | Host names nginx serves (the app, and the media server's signalling host). |
| \`MYSQL_ROOT_PASSWORD\`, \`MYSQL_PASSWORD\`, \`MYSQL_PORT\` | compose | The database container. |
| \`LIVEKIT_WEBHOOK_URL\` | compose profile \`voice\` | Where the LiveKit container sends its webhooks (the server's \`/api/voice/webhook\`). |
| \`SHADOW_DATABASE_URL\` | development (\`prisma migrate dev\`) | An empty database Prisma uses to compute migrations. |
`;
}
