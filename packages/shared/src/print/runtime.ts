/**
 * Runs inside the print page (headless Chromium on the server, or the user's own browser for the
 * offline fallback), after `planner-libs.js`. It draws everything the server-side HTML only marks
 * with placeholders, then sets `window.__PRINT_READY` so the caller knows when to make the PDF.
 */
import { renderPlotSvg } from '../schema/plot';
import type { ChartData, ChartOptions, ChartType, PlotSpec } from '../schema/specs';
import type { PlannerLibs } from './libs-types';

declare global {
  interface Window {
    __PRINT_READY?: boolean;
    __PRINT_ERRORS?: string[];
  }
}

const errors: string[] = [];
const fail = (what: string, e: unknown) => errors.push(`${what}: ${e instanceof Error ? e.message : String(e)}`);

function showError(el: Element, e: unknown) {
  const box = document.createElement('pre');
  box.className = 'diagram-error';
  box.textContent = e instanceof Error ? e.message : String(e);
  el.replaceChildren(box);
}

const readJson = <T>(el: Element, attr: string): T => JSON.parse(el.getAttribute(attr) ?? '{}') as T;
const each = <T extends HTMLElement>(selector: string, fn: (el: T) => void) => document.querySelectorAll<T>(selector).forEach(fn);

async function run(libs: PlannerLibs) {
  document.querySelectorAll('details').forEach((d) => d.setAttribute('open', ''));

  each('[data-type="inline-math"], [data-type="block-math"]', (el) => {
    try {
      libs.katex(el, el.getAttribute('data-latex') ?? '', el.getAttribute('data-type') === 'block-math', false);
    } catch (e) {
      fail('math', e);
    }
  });

  each('pre code', (el) => {
    try {
      libs.highlight(el);
    } catch (e) {
      fail('code', e);
    }
  });

  each('[data-type="chart"]', (el) => {
    try {
      const spec = readJson<{ type: ChartType; data: ChartData; options: ChartOptions }>(el, 'data-chart');
      const canvas = document.createElement('canvas');
      const width = Math.min(el.clientWidth || 640, 720);
      canvas.width = width;
      canvas.height = Math.round(width * 0.5);
      canvas.style.width = `${width}px`;
      canvas.style.height = `${canvas.height}px`;
      el.replaceChildren(canvas);
      // Animations are off, so the chart is fully drawn when this returns.
      libs.chart(canvas, spec.type, spec.data, spec.options ?? {}, { animate: false, responsive: false, devicePixelRatio: 2 });
    } catch (e) {
      showError(el, e);
      fail('chart', e);
    }
  });

  each('[data-type="function-plot"]', (el) => {
    try {
      const { svg, errors: problems } = renderPlotSvg(readJson<PlotSpec>(el, 'data-plot'), { width: Math.min(el.clientWidth || 640, 720) });
      el.innerHTML = svg; // generated by renderPlotSvg: numbers and escaped text only
      problems.forEach((p) => fail('plot', new Error(p)));
    } catch (e) {
      showError(el, e);
      fail('plot', e);
    }
  });

  const diagrams = [...document.querySelectorAll<HTMLElement>('[data-type="mermaid"]')];
  for (const [i, el] of diagrams.entries()) {
    try {
      el.innerHTML = await libs.mermaid(`print-mermaid-${i}`, el.textContent ?? '', false);
    } catch (e) {
      showError(el, e);
      fail('mermaid', e);
    }
  }

  // KaTeX fonts must be loaded before layout is final, or formulas reflow after the PDF is cut.
  await document.fonts?.ready;
}

const libs = window.PlannerLibs;
(libs ? run(libs) : Promise.reject(new Error('planner-libs.js did not load')))
  .catch((e) => fail('runtime', e))
  .finally(() => {
    window.__PRINT_ERRORS = errors;
    window.__PRINT_READY = true;
  });
