import { z } from 'zod';
import type { JSONContent } from '@tiptap/core';
import { colorSchema, iconSchema, idSchema, nameSchema, positionSchema, titleSchema } from './common';

// ---------------------------------------------------------------- responses

export interface NotebookDto {
  id: string;
  /** The space that owns it: the person own space, a team or a project. */
  spaceId: string;
  name: string;
  icon: string | null;
  color: string | null;
  position: string;
  seq: number;
  /** Merge field → seq at which it last changed (phase 15); absent for an entity nobody changed since it was made. */
  fieldSeq?: Record<string, number>;
  deletedAt: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface CategoryDto {
  id: string;
  spaceId: string;
  notebookId: string;
  parentId: string | null;
  name: string;
  position: string;
  seq: number;
  /** Merge field → seq at which it last changed (phase 15); absent for an entity nobody changed since it was made. */
  fieldSeq?: Record<string, number>;
  deletedAt: string | null;
  createdAt: string;
  updatedAt: string;
}

/** Page without its content: what the sidebar and sync pull need. */
export interface PageMetaDto {
  id: string;
  spaceId: string;
  notebookId: string;
  categoryId: string;
  title: string;
  position: string;
  version: number;
  seq: number;
  /** Merge field → seq at which it last changed (phase 15); absent for an entity nobody changed since it was made. */
  fieldSeq?: Record<string, number>;
  deletedAt: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface PageDto extends PageMetaDto {
  content: JSONContent;
  schemaVersion: number;
}

// ---------------------------------------------------------------- create / update bodies
// Ids are generated by the client (UUIDv7) so entities can be created offline.

export const createNotebookSchema = z.object({
  id: idSchema,
  /** Where to create it; the person own space when left out. */
  spaceId: idSchema.optional(),
  name: nameSchema,
  icon: iconSchema.optional(),
  color: colorSchema.optional(),
  position: positionSchema,
});
export type CreateNotebookInput = z.infer<typeof createNotebookSchema>;

export const updateNotebookSchema = z
  .object({ name: nameSchema, icon: iconSchema, color: colorSchema, position: positionSchema })
  .partial();
export type UpdateNotebookInput = z.infer<typeof updateNotebookSchema>;

export const createCategorySchema = z.object({
  id: idSchema,
  notebookId: idSchema,
  parentId: idSchema.nullable().optional(),
  name: nameSchema,
  position: positionSchema,
});
export type CreateCategoryInput = z.infer<typeof createCategorySchema>;

export const updateCategorySchema = z
  .object({ name: nameSchema, parentId: idSchema.nullable(), position: positionSchema })
  .partial();
export type UpdateCategoryInput = z.infer<typeof updateCategorySchema>;

export const createPageSchema = z.object({
  id: idSchema,
  categoryId: idSchema,
  title: titleSchema,
  position: positionSchema,
});
export type CreatePageInput = z.infer<typeof createPageSchema>;

/** Rename and/or move (change category) and/or reorder. The text itself is a co-edited document (phase 11). */
export const updatePageSchema = z
  .object({ title: titleSchema, categoryId: idSchema, position: positionSchema })
  .partial();
export type UpdatePageInput = z.infer<typeof updatePageSchema>;

/**
 * `POST /pages/:id/snapshots/replace`: the page's text becomes this document, as one change on top of what is there (the people
 * in the page see it appear). What a device kept and the server does not have: the Local history's "Replace", a copy it made.
 */
export const replaceContentSchema = z.object({
  content: z.custom<JSONContent>((v) => !!v && typeof v === 'object', 'content must be an object'),
  /** The version the device last saw; with it, a page that changed since answers 409 (with the server's version and text). */
  baseVersion: z.number().int().min(0).optional(),
});
export type ReplaceContentInput = z.infer<typeof replaceContentSchema>;

export interface ReplaceContentOk {
  ok: true;
  version: number;
}
export interface ReplaceContentConflict {
  version: number;
  content: JSONContent;
}

// ---------------------------------------------------------------- search

export const searchQuerySchema = z.object({
  q: z.string().trim().min(1).max(200),
  notebookId: idSchema.optional(),
  limit: z.coerce.number().int().min(1).max(50).default(20),
});

export interface SearchResultDto {
  pageId: string;
  spaceId: string;
  title: string;
  notebookId: string;
  notebookName: string;
  categoryId: string;
  categoryName: string;
  /** Plain-text excerpt; matches are wrapped in [[ ]] markers for the client to highlight. */
  snippet: string;
  score: number;
  updatedAt: string;
}

// ---------------------------------------------------------------- export

export const exportScopeSchema = z.enum(['page', 'category', 'notebook']);
export type ExportScope = z.infer<typeof exportScopeSchema>;

export const exportPdfSchema = z.object({
  scope: exportScopeSchema,
  id: idSchema,
  pageSize: z.enum(['A4', 'Letter']).default('A4'),
  includeToc: z.boolean().default(true),
  /** Language of the cover/TOC labels. */
  locale: z.enum(['en', 'pt']).default('en'),
});
export type ExportPdfInput = z.infer<typeof exportPdfSchema>;

export const exportMarkdownQuerySchema = z.object({
  scope: exportScopeSchema,
  id: idSchema,
});
